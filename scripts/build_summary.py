#!/usr/bin/env python3
"""Build summary.md + summary.json from data.json.

A compact, dated, human- and machine-readable summary of the Prices in Gold
model. Regenerated by the weekly refresh workflow after data.json is built.
Values are copied from the frozen dataset; each row keeps its own as-of date.
Nothing here is real-time.
"""
import json, datetime, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(HERE, "data.json")

PAGE = "https://www.notimeforbull.com/prices/"
DATA = "https://lobstom.github.io/gold-data/data.json"
SUMMARY_JSON = "https://lobstom.github.io/gold-data/summary.json"
SNAPSHOTS = "https://lobstom.github.io/gold-data/snapshots/latest.json"


def fmt_usd(v, big):
    if v is None:
        return None
    if big:
        return f"${v:,.2f} trillion"
    if v >= 1000:
        return f"${v:,.2f}"
    if v >= 100:
        return f"${v:,.2f}"
    return f"${v:,.2f}"


def fmt_native(it, big):
    """Latest value in the row's own unit, as displayed for a reader."""
    v = it.get("usd")
    if v is None:
        return None
    unit = it.get("unit", "")
    sfx = it.get("sfx")
    kind = it.get("kind")
    if kind == "rate" or unit in ("%", "pp"):
        dec = it.get("dec")
        num = f"{v:.{dec}f}" if dec is not None else f"{v:g}"
        return f"{num}{sfx if sfx is not None else '%'}"
    dec = it.get("dec")
    if unit == "ratio":
        return f"{v:.{dec}f}" if dec is not None else f"{v:g}"
    if unit == "index":
        return f"{v:.{dec}f}" if dec is not None else f"{v:g}"
    if unit == "index pt":
        return f"{v:,.1f} pts"
    if unit == "$1":
        return "$1.00"
    if big:
        return f"${v:,.2f} trillion"
    if v >= 1000:
        return f"${v:,.0f} per {unit}"
    return f"${v:,.2f} per {unit}"


def fmt_oz(v, big):
    if not v:
        return None
    if big:
        return f"{v:,.2f} billion oz"
    if v >= 10:
        return f"{v:,.1f} oz"
    if v >= 1:
        return f"{v:,.3f} oz"
    return f"{v:.4g} oz"


def not_gold_priced(o):
    """Rows the dataset itself never converts to gold: rates, ratios, indexes,
    and rows flagged fixed (site: 'Always in index points; conversions do not apply')."""
    return bool(o.get("fixed")) or o.get("kind") == "rate" or o.get("unit") in ("%", "pp", "ratio", "index")


def row(it, override=None):
    o = dict(it)
    if override:
        o.update(override)
    big = bool(o.get("big"))
    out = {
        "id": o["id"],
        "label": o["label"],
        "unit": o.get("unit"),
        "frequency": o.get("freq"),
        "as_of": o.get("asof"),
        "latest_native": fmt_native(o, big),
        "latest_in_gold_oz": None if not_gold_priced(o) else fmt_oz(o.get("ozau"), big),
        "gold_usd_used": o.get("goldusd") or None,
    }
    if o.get("note"):
        out["note"] = o["note"]
    return out


def main():
    d = json.load(open(SRC))
    overrides = d.get("overrides_v3") or {}
    items = [row(it, overrides.get(it["id"])) for it in d["items"]]
    more = [row(it) for it in (d.get("more") or [])]
    more_v3 = [row(it) for it in (d.get("more_v3") or [])]
    byid = {r["id"]: r for r in items + more + more_v3}

    def take(ids):
        return [byid[i] for i in ids if i in byid]

    groups = [
        ("Money", take(["gold", "silver", "usd", "dxy"])),
        ("Commodities and energy", take(["uranium", "wti", "brent", "gas", "ttf", "coal", "elec"])),
        ("Housing", take(["housing", "cshomegold"])),
        ("Markets", take(["sp500", "dow", "ahe", "m2"])),
        ("Debt and the Fed's balance sheet", take(["debt", "publicdebt", "govdebt", "fedassets", "fedtreas", "credit"])),
        ("Interest rates (percent, not priced in gold)", take(["mortgage", "fedfunds", "ust10", "real10", "curve"])),
        ("Ratios and price indexes", take(["gsr", "goldoil", "cpi"])),
    ]

    generated = datetime.date.today().isoformat()
    doc = {
        "name": "Prices in Gold Ounces - model summary",
        "site": "No Time For Bull (notimeforbull.com)",
        "generated": generated,
        "data_updated": d.get("updated"),
        "not_real_time": True,
        "canonical": {"page": PAGE, "data_json": DATA, "summary_json": SUMMARY_JSON, "monday_snapshot_manifest": SNAPSHOTS},
        "groups": [{"group": g, "series": s} for g, s in groups if s],
        "caveats": [v for v in (d.get("v3_notes") or {}).values() if isinstance(v, str)] + [v for v in (d.get("weekly_notes") or {}).values() if isinstance(v, str)],
    }
    with open(os.path.join(HERE, "summary.json"), "w") as f:
        json.dump(doc, f, indent=2)

    L = []
    L.append("# Prices in Gold Ounces - model summary")
    L.append("")
    L.append("No Time For Bull prices commodities, energy, housing, markets, money and debt in troy ounces of gold.")
    L.append("This file is a compact, dated summary of that model. It is generated from the frozen dataset; it is not real-time data.")
    L.append("")
    L.append(f"- Interactive model: {PAGE}")
    L.append(f"- Full dataset (JSON): {DATA}")
    L.append(f"- Machine-readable version of this summary: {SUMMARY_JSON}")
    L.append(f"- Frozen Monday snapshot manifest: {SNAPSHOTS}")
    L.append(f"- Dataset last built: {d.get('updated')}. Summary generated: {generated}.")
    L.append("")
    for g, rows in groups:
        if not rows:
            continue
        L.append(f"## {g}")
        L.append("")
        L.append("| Series | Latest | In gold | As of | Frequency |")
        L.append("| --- | --- | --- | --- | --- |")
        for r in rows:
            L.append(f"| {r['label']} | {r['latest_native'] or '-'} | {r['latest_in_gold_oz'] or 'not priced in gold'} | {r['as_of']} | {r['frequency']} |")
        L.append("")
        for r in rows:
            if r.get("note"):
                n = r["note"]
                L.append(n if n.lower().startswith(r["label"].lower()[:20]) else f"{r['label']}: {n}")
                L.append("")
    L.append("## Sources and conventions")
    L.append("")
    L.append("- Weekly gold: World Gold Council gold price feed, completed-week averages. Monthly gold history before that: World Bank monthly averages.")
    L.append("- Oil, gas, coal, uranium history: World Bank monthly commodities; EIA weekly WTI/Brent; UxC weekly uranium; Cameco month-end uranium history.")
    L.append("- Housing: Census median new-home price (quarterly, FRED MSPUS) from 1963; rescaled Shiller-based index before that. Case-Shiller national index relative to gold, both rebased to 100 in January 2000.")
    L.append("- Rates: Freddie Mac 30Y mortgage (weekly); Fed funds effective rate (discount rate before 1954); Treasury 10Y nominal and 10Y TIPS real yields.")
    L.append("- Markets: S&P 500 and Dow monthly averages plus weekly closes; average hourly earnings; M2 (monthly, seasonally adjusted).")
    L.append("- Debt: federal debt and ownership split from Treasury/Fed sources; Fed balance sheet from H.4.1.")
    L.append("- US Dollar Index rebuilt from Fed G.5 exchange rates with ICE weights, spliced with the Fed major-currencies index before 1980; levels before 1998 are approximate.")
    for n in (d.get("v3_notes") or {}).values():
        if isinstance(n, str):
            L.append(f"- {n}")
    wn = d.get("weekly_notes") or {}
    for n in wn.values():
        if isinstance(n, str):
            L.append(f"- {n}")
    srcmap = wn.get("sources")
    if isinstance(srcmap, dict):
        L.append("- Weekly row sources: " + "; ".join(f"{v}" for k, v in srcmap.items()))
    L.append("")
    L.append("Values priced in gold use the gold price of the same period as each row (weekly rows use weekly averages; monthly rows use monthly averages). Rows carry their own as-of dates and update at their native frequency. Republication rights for underlying sources remain with those sources.")
    L.append("")
    with open(os.path.join(HERE, "summary.md"), "w") as f:
        f.write("\n".join(L))
    print(f"wrote summary.json and summary.md: {sum(len(s) for _, s in groups)} series in {len([g for g, s in groups if s])} groups")


if __name__ == "__main__":
    main()
